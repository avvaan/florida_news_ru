def _norm(text: str) -> str:
    text = text.lower().replace("ё", "е").replace("’", "'")
    text = re.sub(r"\bst\.?\s+(?=[a-z])", "saint ", text)  # St. Petersburg, St Augustine → saint …
    text = re.sub(r"\bft\.?\s+(?=[a-z])", "fort ", text)
    text = re.sub(r"\bdr\.?\s+(?=[a-z])", "dr ", text)
    return " ".join(re.sub(r"[^a-zа-я0-9']+", " ", text).split())


def _build():
    names = {}
    for lat, lon, *aliases in CITIES:
        for alias in aliases:
            names.setdefault(_norm(alias), (lat, lon))
    # Самые длинные названия первыми: «норт майами бич» раньше «майами».
    alternatives = "|".join(re.escape(n) for n in sorted(names, key=len, reverse=True))
    return names, re.compile(rf"(?<![a-zа-я0-9])({alternatives})(?![a-zа-я0-9])")


_NAMES, _CITY_RE = _build()


@lru_cache(maxsize=4096)
def locate(text: str) -> tuple[float, float] | None:
    """Координаты первого города, упомянутого в тексте: «Дирфилд-Бич / Холливуд» → Дирфилд-Бич."""
    if not text:
        return None
    match = _CITY_RE.search(_norm(text))
    return _NAMES[match.group(1)] if match else None


def locate_address(address: str) -> tuple[float, float] | None:
    """Город из американского адреса: часть перед «FL» («…, Deerfield Beach, FL 33441»), а не название улицы."""
    parts = [p.strip() for p in address.split(",")]
    for n, part in enumerate(parts):
        if n and re.fullmatch(r"(FL|Florida)(\s+\d{5}(-\d{4})?)?", part, re.IGNORECASE):
            return locate(parts[n - 1])
    return None


def locate_place(address: str = "", city: str = "") -> tuple[float, float] | None:
    return locate_address(address) or locate(city)


def miles(a: tuple[float, float], b: tuple[float, float]) -> float:
    """Расстояние по прямой в милях (формула гаверсинусов)."""
    lat1, lon1, lat2, lon2 = map(math.radians, (*a, *b))
    h = math.sin((lat2 - lat1) / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin((lon2 - lon1) / 2) ** 2
    return 3958.8 * 2 * math.asin(math.sqrt(h))


def hub_point(hub: str) -> tuple[float, float]:
    return HUBS[hub][3], HUBS[hub][4]


def distance_text(point: tuple[float, float] | None, hub: str) -> str:
    """«≈ 12 миль от Майами»; пусто — если город неизвестен или это сам главный город (и так видно по городу)."""
    if not point or hub not in HUBS:
        return ""
    value = round(miles(point, hub_point(hub)))
    if value < 3:
        return ""
    n = value % 100
    word = "миля" if n % 10 == 1 and n != 11 else "мили" if n % 10 in (2, 3, 4) and not 12 <= n <= 14 else "миль"
    return f"≈ {value} {word} {HUBS[hub][2]}"


def hub_choices() -> list[tuple[str, str]]:
    return [(slug, f"Ближе {to}") for slug, (_, to, *_) in HUBS.items()]


def near_links(request, param: str, prefix: str = "") -> list[dict]:
    """Ссылки «Ближе к Майами»…: меняют только свой параметр (и сбрасывают страницу); повторный клик сбрасывает."""
    current = request.GET.get(param, "")
    links = []
    for slug, label in hub_choices():
        query = request.GET.copy()
        query.pop("page", None)
        value = prefix + slug
        if current == value:
            query.pop(param, None)
        else:
            query[param] = value
        links.append({"label": label, "current": current == value,
                      "url": f"{request.path}?{query.urlencode()}" if query else request.path})
    return links
