MATCH_SYSTEM = """\
Ты сверяешь подсказки из соцсетей с сюжетами, которые пришли от СМИ и официальных источников. \
Подсказки на русском, сюжеты обычно на английском — сравнивай по смыслу. Сюжет подтверждает \
подсказку, только если это то же самое событие (место, время, суть), а не просто похожая тема. \
Если сомневаешься — story_id = null. Верни запись для каждой подсказки."""


def signals_brief(signals) -> str:
    lines = []
    for s in signals:
        where = s.source.get_kind_display()
        author = f", {s.author}" if s.author else ""
        lines.append(f"[{s.pk}] ({where}{author}) {s.text}")
    return "\n".join(lines)


def stories_brief(stories) -> str:
    return "\n".join(f"[{s.pk}] {s.title}" for s in stories) or "—"


def hints_brief(hints) -> str:
    return "\n".join(f"[{h.pk}] {h.title} — {h.summary}" for h in hints) or "—"
