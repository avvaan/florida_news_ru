def region_name(region: str, lang: str) -> str:
    return REGIONS.get(region, {}).get(lang, "")


def human_date(value, lang: str) -> str:
    """«24 ноября 2026» / «24 листопада 2026»."""
    return f"{value.day} {MONTHS[lang][value.month - 1]} {value.year}" if value else ""
