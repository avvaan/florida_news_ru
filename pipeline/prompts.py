def story_brief(items) -> str:
    """Сводка сюжета для промптов: каждый источник отдельным блоком."""
    blocks = []
    for n, item in enumerate(items, 1):
        published = item.published_at.isoformat() if item.published_at else "неизвестно"
        blocks.append(
            f"<source n=\"{n}\" name=\"{item.source.name}\" type=\"{item.source.get_source_type_display()}\" "
            f"published=\"{published}\">\n"
            f"Заголовок: {item.title}\n"
            f"Описание: {item.summary or '—'}\n"
            f"</source>"
        )
    return "\n\n".join(blocks)


def covers_brief(covers, recently_used: set[str]) -> str:
    """Список обложек для выбора: id — описание."""
    from news.covers import describe

    lines = []
    for cover in covers:
        mark = " (недавно была)" if cover.base in recently_used else ""
        lines.append(f"- {cover.base} — {describe(cover)}{mark}")
    return "\n".join(lines)
